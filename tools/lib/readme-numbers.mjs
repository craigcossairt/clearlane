/** Markdown table of the README keys. Throws, naming the key, if numbers.json lacks one. */
export function renderBlock(numbers) {
  const byKey = new Map(numbers.map((n) => [n.key, n]));
  const rows = README_KEYS.map(({ key, label }) => {
    const n = byKey.get(key);
    if (!n) throw new Error(`numbers.json has no key ${key}`);
    return `| ${label} | ${n.display} | ${n.prov} | \`${key}\` |`;
  });
  const days = [...new Set(README_KEYS.map(({ key }) => byKey.get(key).as_of_mt))].sort().join(", ");
  return [
    `Generated by \`node tools/readme-numbers.mjs\` from \`public/derived/numbers.json\` (stage day ${days}). Do not edit by hand.`,
    "",
    "| What | Value | Class | Key |",
    "| --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

/** Replace the text between the one START and the one END marker. */
export function replaceBlock(text, block) {
  const starts = text.split(START).length - 1;
  const ends = text.split(END).length - 1;
  if (starts !== 1 || ends !== 1) {
    throw new Error(`README needs exactly one ${START} and one ${END} marker (found ${starts} and ${ends})`);
  }
  const head = text.slice(0, text.indexOf(START) + START.length);
  const tail = text.slice(text.indexOf(END));
  return `${head}\n${block}\n${tail}`;
}
