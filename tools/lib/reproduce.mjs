// Pure helpers for tools/reproduce.mjs (#32): the input manifest, the JSON diff and docs/NUMBERS.md.
import { createHash } from "node:crypto";

/**
 * Fields never compared, at any depth, with the reason each is excluded.
 * Key order, float formatting and CRLF are pinned instead: the engine writes stableJson
 * (insertion order, JSON.stringify floats, LF), and .gitattributes checks JSON out LF.
 */
export const EXCLUDED_FIELDS = {
  generated_utc: "wall-clock time of the run; reproduce passes the committed value to --now anyway",
  solve_ms: "MEASURED timing; the CLIs print solve times and never store them",
};

/** Also skipped when --fetch compares a re-fetched input: when it was fetched, not what it says. */
export const FETCH_TIME_FIELDS = { fetched_utc: "time of the fetch", retrieved_utc: "time of the fetch" };

/** SHA-256 of a buffer, hex. Line endings are normalized to LF first, so a CRLF checkout hashes the same. */
export function sha256(buf) {
  const text = Buffer.from(buf).toString("latin1").replace(/\r\n/g, "\n");
  return createHash("sha256").update(Buffer.from(text, "latin1")).digest("hex");
}

/** Parses `<sha256>  <path>` lines; blank lines and # comments are skipped. */
export function parseManifest(text) {
  const entries = [];
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const m = /^([0-9a-f]{64})\s+(\S+)$/.exec(line);
    if (!m) throw new Error(`bad manifest line: ${line}`);
    entries.push({ sha: m[1], path: m[2] });
  }
  return entries;
}

/** Manifest text for `{ path: buffer }`, sorted by path. */
export function renderManifest(files) {
  const lines = Object.keys(files)
    .sort()
    .map((p) => `${sha256(files[p])}  ${p}`);
  return `# SHA-256 of every public/data input, LF-normalized. Written by node tools/reproduce.mjs --write-manifest.\n${lines.join("\n")}\n`;
}

/**
 * Paths where two parsed JSON values differ, skipping EXCLUDED_FIELDS.
 * Arrays of objects with a `key` field are matched by key, so a numbers.json change names the stage key.
 */
export function diffJson(a, b, path = "", ignore = EXCLUDED_FIELDS) {
  if (a === b) return [];
  const isObj = (x) => x !== null && typeof x === "object";
  if (!isObj(a) || !isObj(b) || Array.isArray(a) !== Array.isArray(b)) return [path || "(root)"];
  if (Array.isArray(a)) {
    const keyed = (arr) => arr.length > 0 && arr.every((x) => isObj(x) && typeof x.key === "string");
    if (keyed(a) && keyed(b)) {
      const byKey = (arr) => new Map(arr.map((x) => [x.key, x]));
      const ma = byKey(a);
      const mb = byKey(b);
      const out = [];
      for (const k of new Set([...ma.keys(), ...mb.keys()])) {
        if (!ma.has(k) || !mb.has(k)) out.push(`${path}[${k}]`);
        else if (diffJson(ma.get(k), mb.get(k), "", ignore).length) out.push(`${path}[${k}]`);
      }
      const order = (arr) => arr.map((x) => x.key).join("\n");
      if (!out.length && order(a) !== order(b)) out.push(`${path} (key order)`);
      return out;
    }
    if (a.length !== b.length) return [`${path} (length ${a.length} vs ${b.length})`];
    return a.flatMap((x, i) => diffJson(x, b[i], `${path}[${i}]`, ignore));
  }
  const out = [];
  for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) {
    if (k in ignore) continue;
    const p = path ? `${path}.${k}` : k;
    if (!(k in a) || !(k in b)) out.push(p);
    else out.push(...diffJson(a[k], b[k], p, ignore));
  }
  if (!out.length && Object.keys(a).join("\n") !== Object.keys(b).join("\n")) out.push(`${path || "(root)"} (key order)`);
  return out;
}

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

/** docs/NUMBERS.md: every entry of numbers.json, in file order (the engine sorts by key). */
export function renderNumbersDoc(numbers) {
  const days = [...new Set(numbers.map((n) => n.as_of_mt))].sort().join(", ");
  return [
    "# Stage numbers",
    "",
    `Generated by \`node tools/reproduce.mjs --write-docs\` from \`public/derived/numbers.json\` (${numbers.length} numbers, as of ${days}). Do not edit by hand. \`npm run reproduce\` re-derives every one of them offline.`,
    "",
    "| Key | Display | Class | Source | As of (MT) |",
    "| --- | --- | --- | --- | --- |",
    ...numbers.map((n) => `| \`${n.key}\` | ${cell(n.display)} | ${n.prov} | ${cell(n.source)} | ${n.as_of_mt} |`),
    "",
  ].join("\n");
}
